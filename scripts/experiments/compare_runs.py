#!/usr/bin/env python3
"""
compare_runs.py — diff two metrics.json files into a markdown report.

WHAT:
  Reads baseline + candidate metrics.json, produces a comparison.md with:
    - side-by-side final-state table
    - PASS / FAIL against per-metric gates
    - per-iteration delta table
    - inline-rendered curve pointers
  Designed so a downstream paper-writing agent can read this ONE file and
  understand whether the candidate beat / matched / lost to the baseline.

USAGE:
  python scripts/experiments/compare_runs.py \
      --baseline experiments/phase1_pfsp_seed42/metrics.json \
      --candidate experiments/phase1.5_mappo_seed42/metrics.json \
      --out experiments/phase1.5_mappo_seed42/comparison.md
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path


def _load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


# Metric gates. Each entry: (key, baseline-direction, pass_threshold, fail_threshold, label)
# direction = "ge" means higher is better for the candidate; "le" means lower is better.
GATES: list[tuple[str, str, float, float, str]] = [
    ("cum_red",          "ge", 0.75, 0.60, "Cumulative red win share (self-play)"),
    ("eval_kill_rate",   "ge", 0.50, 0.30, "Deterministic eval kill rate @ iter 20"),
    ("aim_res_m",        "le", 0.10, 0.30, "Aim residual (m) — precision"),
    ("adv_std_last",     "le", 50.0, 100.0, "Final advantage std (PPO stability)"),
    ("cmd_pl_last_abs",  "ge", 1e-4, 1e-5,  "Final |cmd policy_loss| (no collapse)"),
]


def _final(metrics: dict) -> dict:
    f = dict(metrics.get("final") or {})
    # absolute value for cmd_pl collapse check
    f["cmd_pl_last_abs"] = abs(f.get("cmd_pl_last", 0.0))
    return f


def _verdict(baseline_val: float, cand_val: float, direction: str,
             pass_thr: float, fail_thr: float) -> str:
    if direction == "ge":
        if cand_val >= pass_thr:
            return "PASS"
        if cand_val < fail_thr:
            return "FAIL"
        return "MARGINAL"
    else:  # le
        if cand_val <= pass_thr:
            return "PASS"
        if cand_val > fail_thr:
            return "FAIL"
        return "MARGINAL"


def render(baseline: dict, candidate: dict,
           baseline_name: str, candidate_name: str,
           out_path: Path) -> str:
    bf = _final(baseline)
    cf = _final(candidate)

    lines: list[str] = []
    lines.append(f"# Comparison: {candidate_name} vs {baseline_name}\n")
    lines.append(f"_Generated by `scripts/experiments/compare_runs.py`_\n")
    lines.append(f"_Baseline:  `{baseline['log_path']}`  (iters={baseline['iter_count']})_")
    lines.append(f"_Candidate:  `{candidate['log_path']}`  (iters={candidate['iter_count']})_\n")

    lines.append("## Final-state headline\n")
    lines.append("| Metric | " + baseline_name + " | " + candidate_name +
                 " | Direction | Gate (PASS / FAIL) |")
    lines.append("|---|---|---|---|---|")
    overall_pass = True
    overall_marginal = False
    for key, direction, pass_thr, fail_thr, label in GATES:
        b = bf.get(key, float("nan"))
        c = cf.get(key, float("nan"))
        verdict = _verdict(b, c, direction, pass_thr, fail_thr)
        if verdict == "FAIL":
            overall_pass = False
        if verdict == "MARGINAL":
            overall_pass = False
            overall_marginal = True
        arrow = "↑" if direction == "ge" else "↓"
        lines.append(f"| {label} | {b:.4g} | {c:.4g} | {arrow} | "
                     f"{verdict} (thr: {pass_thr}) |")
    lines.append("")
    overall = "PASS ✅" if overall_pass else ("MARGINAL ⚠️" if overall_marginal else "FAIL ❌")
    lines.append(f"**Overall verdict: {overall}**\n")

    lines.append("## Gate definitions\n")
    lines.append("- **PASS**: candidate meets the PASS threshold on every metric.")
    lines.append("- **MARGINAL**: at least one metric is between PASS and FAIL thresholds.")
    lines.append("- **FAIL**: at least one metric crosses the FAIL threshold (degradation).\n")

    # Per-iter delta table — last 5 iters
    lines.append("## Per-iteration delta (last 5 iters)\n")
    lines.append("| iter | " + baseline_name + " kr | " + candidate_name +
                 " kr | Δ kr | " + baseline_name + " cum_red | " +
                 candidate_name + " cum_red | Δ cum_red |")
    lines.append("|---|---|---|---|---|---|---|")
    b_iters = {r["iter"]: r for r in baseline["per_iter"]}
    c_iters = {r["iter"]: r for r in candidate["per_iter"]}
    b_evals = {r["iter"]: r for r in baseline["per_eval"]}
    c_evals = {r["iter"]: r for r in candidate["per_eval"]}
    common = sorted(set(b_iters.keys()) & set(c_iters.keys()))[-5:]
    for it in common:
        bkr = b_iters[it]["kr_m"]
        ckr = c_iters[it]["kr_m"]
        bcr = b_evals.get(it, {}).get("cum_red", float("nan"))
        ccr = c_evals.get(it, {}).get("cum_red", float("nan"))
        lines.append(f"| {it} | {bkr:.3g}m | {ckr:.3g}m | {ckr-bkr:+.3g}m | "
                     f"{bcr:.3g} | {ccr:.3g} | {ccr-bcr:+.3g} |")
    lines.append("")

    lines.append("## Figures\n")
    lines.append("Run the following to regenerate all curve overlays:")
    lines.append("```bash")
    lines.append(f"python scripts/experiments/make_figures.py \\")
    lines.append(f"    --run {baseline_name}:experiments/phase1_pfsp_seed42/metrics.json \\")
    lines.append(f"    --run {candidate_name}:experiments/{candidate['run_id']}/metrics.json \\")
    lines.append(f"    --out-dir experiments/{candidate['run_id']}/figures")
    lines.append("```\n")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", required=True, type=Path)
    ap.add_argument("--candidate", required=True, type=Path)
    ap.add_argument("--baseline-name", default=None)
    ap.add_argument("--candidate-name", default=None)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    b = _load(args.baseline)
    c = _load(args.candidate)
    bname = args.baseline_name or b["run_id"]
    cname = args.candidate_name or c["run_id"]
    text = render(b, c, bname, cname, args.out)
    print(f"wrote {args.out}")
    print("\n--- summary ---")
    for line in text.splitlines():
        if "Overall verdict" in line:
            print(line)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
